CREATE TABLE chart_of_accounts (
  account_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_code      VARCHAR(10) NOT NULL UNIQUE,
  account_name      VARCHAR(100) NOT NULL,
  account_type      VARCHAR(20) NOT NULL CHECK (account_type IN ('Asset','Liability','Equity','Revenue','Expense')),
  is_active         BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE departments (
  department_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_code   VARCHAR(10) NOT NULL UNIQUE,
  department_name   VARCHAR(100) NOT NULL,
  cost_center       VARCHAR(20) NOT NULL
);

CREATE TABLE vendors (
  vendor_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vendor_name       VARCHAR(150) NOT NULL,
  vendor_type       VARCHAR(30) NOT NULL CHECK (vendor_type IN ('Software','Facilities','Professional Services','Utilities','Logistics','Marketing','Other')),
  payment_terms     VARCHAR(20) NOT NULL CHECK (payment_terms IN ('Net 15','Net 30','Net 45','Due on receipt')),
  city              VARCHAR(80),
  state             VARCHAR(20)
);

CREATE TABLE customers (
  customer_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_name     VARCHAR(150) NOT NULL,
  segment           VARCHAR(30) NOT NULL CHECK (segment IN ('Enterprise','Mid-Market','SMB','Public Sector')),
  city              VARCHAR(80),
  state             VARCHAR(20)
);

CREATE TABLE invoices (
  invoice_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number    VARCHAR(20) NOT NULL UNIQUE,
  customer_id       INT NOT NULL REFERENCES customers(customer_id),
  invoice_date      DATE NOT NULL,
  due_date          DATE NOT NULL,
  status            VARCHAR(15) NOT NULL CHECK (status IN ('Open','Paid','Partially Paid','Void')),
  currency          CHAR(3) NOT NULL DEFAULT 'USD',
  memo              VARCHAR(200)
);

CREATE TABLE invoice_lines (
  invoice_line_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id        INT NOT NULL REFERENCES invoices(invoice_id) ON DELETE CASCADE,
  line_number       INT NOT NULL,
  description       VARCHAR(200) NOT NULL,
  department_id     INT NOT NULL REFERENCES departments(department_id),
  revenue_account_id INT NOT NULL REFERENCES chart_of_accounts(account_id),
  amount            NUMERIC(12,2) NOT NULL CHECK (amount >= 0)
);

CREATE TABLE bills (
  bill_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bill_number       VARCHAR(20) NOT NULL UNIQUE,
  vendor_id         INT NOT NULL REFERENCES vendors(vendor_id),
  bill_date         DATE NOT NULL,
  due_date          DATE NOT NULL,
  status            VARCHAR(15) NOT NULL CHECK (status IN ('Open','Paid','Partially Paid','Void')),
  currency          CHAR(3) NOT NULL DEFAULT 'USD',
  memo              VARCHAR(200)
);

CREATE TABLE bill_lines (
  bill_line_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bill_id           INT NOT NULL REFERENCES bills(bill_id) ON DELETE CASCADE,
  line_number       INT NOT NULL,
  description       VARCHAR(200) NOT NULL,
  department_id     INT NOT NULL REFERENCES departments(department_id),
  expense_account_id INT NOT NULL REFERENCES chart_of_accounts(account_id),
  amount            NUMERIC(12,2) NOT NULL CHECK (amount >= 0)
);

CREATE TABLE payments (
  payment_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_number    VARCHAR(20) NOT NULL UNIQUE,
  payment_date      DATE NOT NULL,
  payment_type      VARCHAR(10) NOT NULL CHECK (payment_type IN ('AR','AP')),
  customer_id       INT REFERENCES customers(customer_id),
  vendor_id         INT REFERENCES vendors(vendor_id),
  method            VARCHAR(20) NOT NULL CHECK (method IN ('ACH','Wire','Check','Card')),
  amount            NUMERIC(12,2) NOT NULL CHECK (amount > 0),
  memo              VARCHAR(200),
  CHECK (
    (payment_type = 'AR' AND customer_id IS NOT NULL AND vendor_id IS NULL)
    OR
    (payment_type = 'AP' AND vendor_id IS NOT NULL AND customer_id IS NULL)
  )
);

CREATE TABLE payment_applications (
  payment_application_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id        INT NOT NULL REFERENCES payments(payment_id) ON DELETE CASCADE,
  apply_to_type     VARCHAR(10) NOT NULL CHECK (apply_to_type IN ('Invoice','Bill')),
  invoice_id        INT REFERENCES invoices(invoice_id),
  bill_id           INT REFERENCES bills(bill_id),
  applied_amount    NUMERIC(12,2) NOT NULL CHECK (applied_amount > 0),
  CHECK (
    (apply_to_type = 'Invoice' AND invoice_id IS NOT NULL AND bill_id IS NULL)
    OR
    (apply_to_type = 'Bill' AND bill_id IS NOT NULL AND invoice_id IS NULL)
  )
);

CREATE TABLE journal_entries (
  journal_entry_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_number    VARCHAR(20) NOT NULL UNIQUE,
  entry_date        DATE NOT NULL,
  description       VARCHAR(200) NOT NULL,
  source            VARCHAR(30) NOT NULL CHECK (source IN ('Manual','Accrual','Payroll','Depreciation','Reclass'))
);

CREATE TABLE journal_lines (
  journal_line_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_entry_id  INT NOT NULL REFERENCES journal_entries(journal_entry_id) ON DELETE CASCADE,
  line_number       INT NOT NULL,
  account_id        INT NOT NULL REFERENCES chart_of_accounts(account_id),
  department_id     INT REFERENCES departments(department_id),
  debit             NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
  credit            NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
  CHECK (NOT (debit > 0 AND credit > 0)),
  CHECK (debit > 0 OR credit > 0)
);

