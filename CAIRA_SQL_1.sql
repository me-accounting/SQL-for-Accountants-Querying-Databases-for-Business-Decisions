-- Sign convention:
--   Revenue positive
--   Expense negative
-- =========================================================

CREATE VIEW v_finance_activity AS
SELECT
  'AR' AS source,
  i.invoice_date AS txn_date,
  to_char(i.invoice_date, 'YYYY-MM') AS txn_month,
  i.invoice_number AS document_number,
  c.customer_name AS counterparty,
  d.department_name,
  coa.account_code,
  coa.account_name,
  coa.account_type,
  il.amount AS amount
FROM invoices i
JOIN customers c ON c.customer_id = i.customer_id
JOIN invoice_lines il ON il.invoice_id = i.invoice_id
JOIN departments d ON d.department_id = il.department_id
JOIN chart_of_accounts coa ON coa.account_id = il.revenue_account_id

UNION ALL

SELECT
  'AP' AS source,
  b.bill_date AS txn_date,
  to_char(b.bill_date, 'YYYY-MM') AS txn_month,
  b.bill_number AS document_number,
  v.vendor_name AS counterparty,
  d.department_name,
  coa.account_code,
  coa.account_name,
  coa.account_type,
  (bl.amount * -1) AS amount
FROM bills b
JOIN vendors v ON v.vendor_id = b.vendor_id
JOIN bill_lines bl ON bl.bill_id = b.bill_id
JOIN departments d ON d.department_id = bl.department_id
JOIN chart_of_accounts coa ON coa.account_id = bl.expense_account_id

UNION ALL

SELECT
  'JE' AS source,
  je.entry_date AS txn_date,
  to_char(je.entry_date, 'YYYY-MM') AS txn_month,
  je.journal_number AS document_number,
  je.description AS counterparty,
  COALESCE(d.department_name, 'Unassigned') AS department_name,
  coa.account_code,
  coa.account_name,
  coa.account_type,
  (jl.debit - jl.credit) AS amount
FROM journal_entries je
JOIN journal_lines jl ON jl.journal_entry_id = je.journal_entry_id
JOIN chart_of_accounts coa ON coa.account_id = jl.account_id
LEFT JOIN departments d ON d.department_id = jl.department_id;

