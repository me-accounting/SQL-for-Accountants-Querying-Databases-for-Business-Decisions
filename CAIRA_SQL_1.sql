-- AP payments derived from bill totals
WITH bill_totals AS (
  SELECT
    b.bill_id,
    b.vendor_id,
    b.bill_date,
    b.status,
    sum(bl.amount)::numeric(12,2) AS total_amount
  FROM bills b
  JOIN bill_lines bl ON bl.bill_id = b.bill_id
  WHERE b.status IN ('Paid','Partially Paid')
  GROUP BY b.bill_id, b.vendor_id, b.bill_date, b.status
),
pay AS (
  SELECT
    bill_id,
    vendor_id,
    (bill_date + (7 + det_int('ap_pay_delay_'||bill_id, 25)) * INTERVAL '1 day')::date AS payment_date,
    CASE det_int('ap_method_'||bill_id, 4)
      WHEN 0 THEN 'ACH'
      WHEN 1 THEN 'Wire'
      WHEN 2 THEN 'Check'
      ELSE 'Card'
    END AS method,
    CASE
      WHEN status = 'Paid' THEN total_amount
      ELSE round(total_amount * (0.35 + det_int('ap_partial_'||bill_id, 46)::numeric / 100), 2) -- 0.35 to 0.80
    END AS paid_amount
  FROM bill_totals
)
INSERT INTO payments (payment_number, payment_date, payment_type, vendor_id, method, amount, memo)
SELECT
  'PMT-AP-' || to_char(bill_id, 'FM00000') AS payment_number,
  payment_date,
  'AP',
  vendor_id,
  method,
  paid_amount,
  'Payment for bill ' || (SELECT bill_number FROM bills WHERE bill_id = pay.bill_id)
FROM pay;

