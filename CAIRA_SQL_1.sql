-- AR payments derived from invoice totals
WITH inv_totals AS (
  SELECT
    i.invoice_id,
    i.customer_id,
    i.invoice_date,
    i.status,
    sum(il.amount)::numeric(12,2) AS total_amount
  FROM invoices i
  JOIN invoice_lines il ON il.invoice_id = i.invoice_id
  WHERE i.status IN ('Paid','Partially Paid')
  GROUP BY i.invoice_id, i.customer_id, i.invoice_date, i.status
),
pay AS (
  SELECT
    invoice_id,
    customer_id,
    (invoice_date + (5 + det_int('ar_pay_delay_'||invoice_id, 20)) * INTERVAL '1 day')::date AS payment_date,
    CASE det_int('ar_method_'||invoice_id, 4)
      WHEN 0 THEN 'ACH'
      WHEN 1 THEN 'Wire'
      WHEN 2 THEN 'Check'
      ELSE 'Card'
    END AS method,
    CASE
      WHEN status = 'Paid' THEN total_amount
      ELSE round(total_amount * (0.40 + det_int('ar_partial_'||invoice_id, 41)::numeric / 100), 2) -- 0.40 to 0.80
    END AS paid_amount
  FROM inv_totals
)
INSERT INTO payments (payment_number, payment_date, payment_type, customer_id, method, amount, memo)
SELECT
  'PMT-AR-' || to_char(invoice_id, 'FM00000') AS payment_number,
  payment_date,
  'AR',
  customer_id,
  method,
  paid_amount,
  'Payment for invoice ' || (SELECT invoice_number FROM invoices WHERE invoice_id = pay.invoice_id)
FROM pay;

-- Apply AR payments to invoices
