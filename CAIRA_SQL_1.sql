-- ---------- Deterministic helpers ----------
-- Returns deterministic integer in [0, mod-1]
CREATE FUNCTION det_int(seed text, mod int)
RETURNS int
LANGUAGE SQL
IMMUTABLE
AS $$
  SELECT ( (('x' || substr(md5(seed), 1, 8))::bit(32)::int) % mod + mod ) % mod;
$$;

-- Returns deterministic numeric in [min_val, max_val]
CREATE FUNCTION det_num(seed text, min_val numeric, max_val numeric)
RETURNS numeric
LANGUAGE SQL
IMMUTABLE
AS $$
  SELECT round(min_val + (det_int(seed, 100000)::numeric / 100000) * (max_val - min_val), 2);
$$;

