    (SELECT department_id FROM departments WHERE department_code='FIN') AS fin,
    (SELECT department_id FROM departments WHERE department_code='SAL') AS sal,
    (SELECT department_id FROM departments WHERE department_code='MKT') AS mkt,
    (SELECT department_id FROM departments WHERE department_code='OPS') AS ops
)

INSERT INTO journal_lines (journal_entry_id, line_number, account_id, department_id, debit, credit)

-- Line 1: Debit
SELECT
  je.journal_entry_id,
  1 AS line_number,
  CASE
    WHEN je.source = 'Accrual' THEN acct.contractor_exp
    WHEN je.source = 'Depreciation' THEN acct.depr_exp
    WHEN je.source = 'Reclass' THEN acct.sal_exp
    WHEN je.source = 'Payroll' THEN acct.sal_exp
    ELSE acct.contractor_exp
  END AS account_id,
  CASE
    WHEN je.source = 'Reclass' THEN depts.sal
    WHEN je.source = 'Depreciation' THEN depts.ops
    WHEN je.source = 'Accrual' THEN depts.fin
    ELSE depts.ops
  END AS department_id,
  je.amount AS debit,
  0::numeric AS credit
FROM je, acct, depts

UNION ALL

-- Line 2: Credit (same amount, opposite side)
SELECT
  je.journal_entry_id,
  2 AS line_number,
  CASE
    WHEN je.source = 'Accrual' THEN acct.accrued_exp
    WHEN je.source = 'Depreciation' THEN acct.accum_depr
    WHEN je.source = 'Reclass' THEN acct.mkt_exp
    WHEN je.source = 'Payroll' THEN acct.cash
    ELSE acct.accrued_exp
  END AS account_id,
  CASE
    WHEN je.source = 'Reclass' THEN depts.mkt
    WHEN je.source = 'Depreciation' THEN depts.ops
    WHEN je.source = 'Accrual' THEN depts.fin
    ELSE NULL
  END AS department_id,
  0::numeric AS debit,
  je.amount AS credit
FROM je, acct, depts;

